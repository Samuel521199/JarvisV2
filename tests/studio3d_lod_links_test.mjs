import assert from 'node:assert/strict';
import {gameLodEntries,gameLodLabel} from '../apps/workbench/studio3d-lod-links.js';
const rows=[0,1,2,3].map(level=>({level,job_id:String(level+1).repeat(32),sha256:String(level+1).repeat(64),triangles:Math.floor(60000/(level+1))}));
const bundle={schema:'jarvis.game-lod-pages.v1',source_sha256:'a'.repeat(64),levels:rows};
assert.deepEqual(gameLodEntries(null,'x','x'),[]);
assert.equal(gameLodEntries(bundle,rows[0].job_id,rows[0].sha256).length,4);
assert.throws(()=>gameLodEntries(bundle,'b'.repeat(32),rows[0].sha256));
assert.throws(()=>gameLodEntries({...bundle,levels:[...rows.slice(0,3),rows[0]]},rows[0].job_id,rows[0].sha256));
assert.throws(()=>gameLodEntries({...bundle,levels:rows.map((r,i)=>i===3?{...r,job_id:'https://evil'}:r)},rows[0].job_id,rows[0].sha256));
const high={job_id:'e'.repeat(32),sha256:'f'.repeat(64),triangles:575538};
const withHigh={...bundle,high};
const options=gameLodEntries(withHigh,rows[3].job_id,rows[3].sha256);
assert.equal(options.length,5);assert.equal(options[0].kind,'high');assert.deepEqual(options.slice(1).map(r=>r.level),[0,1,2,3]);
assert.equal(gameLodEntries(withHigh,high.job_id,high.sha256).length,5);
assert.equal(gameLodLabel(options[0]),'原始高模 · '+(575538).toLocaleString()+' 三角面');
assert.equal(gameLodLabel(options[1]),'LOD0 · '+rows[0].triangles.toLocaleString()+' 三角面');
assert.throws(()=>gameLodEntries(withHigh,high.job_id,'a'.repeat(64)));
for(const bad of [null,{...high,job_id:rows[0].job_id},{...high,job_id:'https://evil'},{...high,sha256:'wrong'},{...high,triangles:true}])assert.throws(()=>gameLodEntries({...bundle,high:bad},rows[0].job_id,rows[0].sha256));
console.log('PASS: original high <-> four receipt-bound LOD pages; legacy four-only bundle preserved; mismatched SHA, duplicates, invalid triangles and external destinations rejected');
